/// Renders the content of each of `files`.
fn render<F: File>(files: impl Iterator<Item = F>) -> Result<Vec<wit::File>, String> {
    files
        .map(|file| {
            let content = file.content().map_err(|err| format!("{}: {err}", file.path()))?;
            Ok(wit::File {
                path: file.path().to_owned(),
                content: content.into_owned(),
            })
        })
        .collect()
}

