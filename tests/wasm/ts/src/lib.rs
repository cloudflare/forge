/// `forge::plugin`: the traits from src/plugin.rs, and the `ts` library.
#[path = "../../../../src/plugin"]
pub mod plugin {
    use std::borrow::Cow;

    use crate::{Forge, Group};

    pub mod ts;

    /// The error that plugins and files return.
    pub type Err = Box<dyn std::error::Error + Send + Sync + 'static>;

    /// A plugin that generates files.
    pub trait Plugin: Sync {
        type File: File;

        fn generate(&self, _: &Forge) -> Result<impl Iterator<Item = Self::File>, Err> {
            Ok(std::iter::empty())
        }

        fn generate_group(&self, _: Group<'_>) -> Result<impl Iterator<Item = Self::File>, Err> {
            Ok(std::iter::empty())
        }
    }

    /// A file generated by a plugin.
    pub trait File: Send {
        fn path(&self) -> &str;
        fn content(&self) -> Result<Cow<'_, [u8]>, Err>;
    }
}

