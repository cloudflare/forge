impl<'f> Body<'f> {
    pub fn is_required(self) -> bool {
        self.data.required
    }

    pub fn description(self) -> &'f str {
        &self.data.description
    }

    pub fn contents(self) -> impl ExactSizeIterator<Item = Content<'f>> {
        let forge = self.forge;
        self.data.contents.iter().map(move |data| Content { forge, data })
    }

    pub fn json(self) -> Option<Content<'f>> {
        Some(Content {
            forge: self.forge,
            data: &self.data.contents[self.data.json? as usize],
        })
    }
}

impl<'f> Response<'f> {
    pub fn status(self) -> &'f str {
        &self.data.status
    }

    pub fn description(self) -> &'f str {
        &self.data.description
    }

    pub fn contents(self) -> impl ExactSizeIterator<Item = Content<'f>> {
        let forge = self.forge;
        self.data.contents.iter().map(move |data| Content { forge, data })
    }

    pub fn json(self) -> Option<Content<'f>> {
        Some(Content {
            forge: self.forge,
            data: &self.data.contents[self.data.json? as usize],
        })
    }
}

impl<'f> Content<'f> {
    pub fn media_type(self) -> &'f str {
        &self.data.media_type
    }

    pub fn description(self) -> &'f str {
        &self.data.description
    }

    pub fn is_json(self) -> bool {
        let base = self.media_type().split(';').next().unwrap_or_default().trim();
        let base = base.to_ascii_lowercase();
        base == "application/json" || base.ends_with("+json")
    }

    pub fn ty(self) -> Type<'f> {
        Type::new(self.forge, self.data.ty)
    }
}

