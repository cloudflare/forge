struct Component;

/// Everything the API gives, from tests/wasm/dump.rs, which tests/wasm.rs
/// compares with forge's own.
#[cfg(feature = "dump")]
#[path = "../../dump.rs"]
mod dump;

impl wit::Guest for Component {
    /// With the `dump` feature, returns the dump of the forge instead, as
    /// `dump.txt`.
    #[cfg(feature = "dump")]
    fn generate(forge_bytes: Vec<u8>) -> Result<Vec<wit::File>, String> {
        let forge = Forge::from_bytes(forge_bytes);
        Ok(vec![wit::File {
            path: "dump.txt".to_owned(),
            content: dump::dump(&forge).into_bytes(),
        }])
    }

    #[cfg(not(feature = "dump"))]
    fn generate(forge_bytes: Vec<u8>) -> Result<Vec<wit::File>, String> {
        let forge = Forge::from_bytes(forge_bytes);
        render(bin::ts::Generator.generate(&forge).map_err(|err| err.to_string())?)
    }
}
wit::export!(Component with_types_in wit);

/// Renders the content of each of `files`.
fn render<F: File>(files: impl Iterator<Item = F>) -> Result<Vec<wit::File>, String> {
    files
        .map(|file| {
            let content = file.content().map_err(|err| format!("{}: {err}", file.path()))?;
            Ok(wit::File {
                path: file.path().to_owned(),
                content: content.into_owned(),
            })
        })
        .collect()
}

