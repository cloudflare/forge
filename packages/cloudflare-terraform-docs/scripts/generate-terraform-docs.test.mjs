test('parseSdkApiMarkdown maps SDK accessors to documented endpoints', () => {
  const endpoints = parseSdkApiMarkdown(API_MD);
  assert.equal(endpoints.get('Widgets.New'), 'post /accounts/{account_id}/widgets');
  assert.equal(endpoints.get('Widgets.Delete'), 'delete /accounts/{account_id}/widgets/{widget_id}');
  assert.equal(endpoints.size, 4);
});

test('parseServiceSource records the type name, SDK module and lifecycle role of each call', () => {
  const resource = parseServiceSource(RESOURCE_GO, 'resource');
  assert.equal(resource?.name, 'cloudflare_widget');
  assert.equal(resource?.sdkModule, 'github.com/cloudflare/cloudflare-go/v7');
  assert.deepEqual(resource?.calls, [
    { call: 'Widgets.New', role: 'create' },
    { call: 'Widgets.Get', role: 'read' },
    { call: 'Widgets.Delete', role: 'delete' },
    { call: 'Widgets.Get', role: 'import' },
  ]);
  const list = parseServiceSource(LIST_GO, 'list-data-source');
  assert.deepEqual(list?.calls[0], { call: 'Widgets.List', role: 'read' });
  assert.equal(parseServiceSource('package nothing', 'resource'), undefined);
});

test('parseDeclarationMarkdown reads tfplugindocs groups, flags and nested schemas', () => {
  const doc = parseDeclarationMarkdown(WIDGET_MD, 'docs/resources/widget.md');
  assert.equal(doc.name, 'cloudflare_widget');
  assert.equal(doc.description, 'Manages a widget.\n\n- `Widget Write`');
  assert.deepEqual(doc.required, [
    { name: 'account_id', type: 'String' },
    { name: 'name', type: 'String', description: 'Widget name.\nAvailable values: "a", "b".' },
  ]);
  assert.deepEqual(
    doc.optional.map(({ name, sensitive }) => [name, sensitive ?? false]),
    [
      ['secret', true],
      ['settings', false],
      ['token', true],
    ],
  );
  assert.deepEqual(doc.optional[1], {
    name: 'settings',
    type: 'Attributes',
    description: 'Widget settings.',
    children: [
      { name: 'enabled', type: 'Boolean', description: 'Whether it is enabled.', deprecated: 'Deprecated.' },
      { name: 'mode', type: 'Attributes', description: 'Mode.', children: [{ name: 'value', type: 'Number' }] },
    ],
  });
  assert.deepEqual(
    doc.computed.map(({ name, type }) => [name, type]),
    [
      ['id', 'String'],
      ['tags', 'List of String'],
    ],
  );
});

test('parseDeclarationMarkdown fails with file:line on anything unexpected', () => {
  const file = 'docs/resources/widget.md';
  const lineOf = (needle) => WIDGET_MD.split('\n').findIndex((line) => line.includes(needle)) + 1;
  const cases = [
    [WIDGET_MD.replace('(String, Sensitive) A secret', '(String, Secret) A secret'), /unknown attribute flag "Secret"/],
    [WIDGET_MD.replace('(#nestedatt--settings--mode)', '(#nestedatt--nope)'), /references missing nested schema/],
    [WIDGET_MD.replace('<!-- schema generated by tfplugindocs -->', ''), /missing `<!-- schema generated/],
    [WIDGET_MD.replace('### Optional\n\n', '### Optional\n\nSome prose\n'), /unexpected line in schema/],
    [WIDGET_MD.replace('Optional:\n\n- `mode`', '### Optional\n\n- `mode`'), /`### Optional` inside a nested schema/],
    [
      WIDGET_MD.replace(' (see [below for nested schema](#nestedatt--settings--mode))', ''),
      /#nestedatt--settings--mode is not referenced/,
    ],
  ];
  for (const [markdown, message] of cases) {
    assert.throws(() => parseDeclarationMarkdown(markdown, file), message);
  }
  assert.throws(
    () =>
      parseDeclarationMarkdown(WIDGET_MD.replace('(String, Sensitive) A secret', '(String, Secret) A secret'), file),
    new RegExp(`^Error: ${file}:${lineOf('`secret`')}: unknown attribute flag`),
  );
});

test('buildTerraformDocs links declarations to endpoints by role and reports gaps', () => {
  const module = 'github.com/cloudflare/cloudflare-go/v7';
  const files = {
    'docs/resources/widget.md': WIDGET_MD,
    'docs/data-sources/widgets.md': WIDGETS_MD,
    'examples/resources/cloudflare_widget/resource.tf': 'resource "cloudflare_widget" "example" {}\n',
    'examples/resources/cloudflare_widget/import.sh': "$ terraform import cloudflare_widget.example '<id>'\n",
  };
  const docs = buildTerraformDocs({
    provider: { repository: 'https://example.com/provider', version: '1.2.3' },
    sdks: [{ module, version: 'v7.0.0' }],
    services: [
      parseServiceSource(RESOURCE_GO, 'resource'),
      parseServiceSource(LIST_GO, 'list-data-source'),
      { kind: 'resource', name: 'cloudflare_unreleased', sdkModule: module, calls: [] },
    ],
    sdkEndpoints: new Map([[module, parseSdkApiMarkdown(API_MD)]]),
    readProviderFile: (file) => files[file],
  });

  assert.deepEqual(Object.keys(docs.declarations), [
    'resource:cloudflare_widget',
    'list-data-source:cloudflare_widgets',
  ]);
  assert.equal(docs.declarations['resource:cloudflare_widget'].example, 'resource "cloudflare_widget" "example" {}');
  assert.deepEqual(docs.undocumented, ['resource:cloudflare_unreleased']);
  assert.deepEqual(docs.endpoints['get /accounts/{account_id}/widgets/{widget_id}'], [
    { declaration: 'resource:cloudflare_widget', roles: ['read', 'import'] },
  ]);
  assert.deepEqual(docs.endpoints['get /accounts/{account_id}/widgets'], [
    { declaration: 'list-data-source:cloudflare_widgets', roles: ['read'] },
  ]);
  assert.deepEqual(docs.unresolvedCalls, [
    { declaration: 'list-data-source:cloudflare_widgets', call: `${module} Widgets.Rename` },
  ]);
  assert.deepEqual(docs.stats, { declarations: 2, linkedDeclarations: 2, endpoints: 4, unresolvedCalls: 1 });
  assert.throws(
    () =>
      buildTerraformDocs({
        provider: { repository: 'https://example.com/provider', version: '1.2.3' },
        sdks: [],
        services: [parseServiceSource(RESOURCE_GO, 'resource')],
        sdkEndpoints: new Map(),
        readProviderFile: (file) => (file === 'docs/resources/widget.md' ? WIDGETS_MD : undefined),
      }),
    /documents cloudflare_widgets, expected cloudflare_widget/,
  );
});

