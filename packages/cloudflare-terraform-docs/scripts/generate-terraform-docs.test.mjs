test('versions come from go.mod and release-please version files', () => {
  const requirements = parseSdkRequirements(`module x
require (
	github.com/cloudflare/cloudflare-go v0.118.0
	github.com/cloudflare/cloudflare-go/v6 v6.10.0
	github.com/cloudflare/cloudflare-go/v7 v7.12.1-0.20261001120000-0123456789ab
)`);
  assert.deepEqual(
    [...requirements],
    [
      ['github.com/cloudflare/cloudflare-go/v6', 'v6.10.0'],
      ['github.com/cloudflare/cloudflare-go/v7', 'v7.12.1-0.20261001120000-0123456789ab'],
    ],
  );
  assert.equal(
    parsePackageVersion('package internal\n\nconst PackageVersion = "5.27.0" // x-release-please-version\n', 'p'),
    '5.27.0',
  );
  assert.throws(() => parsePackageVersion('package internal', 'provider'), /provider: internal\/version.go/);
});

test('checkReportedVersion tolerates only a patch mismatch with the tag', () => {
  assert.equal(checkReportedVersion('provider', '5.28.1', '5.28.1'), undefined);
  assert.equal(checkReportedVersion('sdk', 'v7.13.1', '7.13.1'), undefined);
  assert.match(
    checkReportedVersion('provider', '5.28.1', '5.28.0'),
    /^provider: v5\.28\.1 checkout reports version 5\.28\.0/,
  );
  assert.match(checkReportedVersion('sdk', 'v7.13.1', '7.13.0'), /^sdk: v7\.13\.1 checkout reports version 7\.13\.0/);
  assert.throws(
    () => checkReportedVersion('provider', '5.29.0', '5.28.0'),
    /v5\.29\.0 checkout reports version 5\.28\.0/,
  );
  assert.throws(() => checkReportedVersion('provider', '6.0.0', '5.28.0'), /checkout reports version/);
  assert.throws(() => checkReportedVersion('provider', '5.28.1', '5.28.1-beta.1'), /checkout reports version/);
  assert.throws(
    () => checkReportedVersion('sdk', 'v7.12.1-0.20261001120000-0123456789ab', '7.12.0'),
    /checkout reports version/,
  );
});

test('SourceTree confines reads to the checkout and never follows symbolic links', async (t) => {
  const base = await mkdtemp(path.join(os.tmpdir(), 'source-tree-'));
  t.after(() => rm(base, { recursive: true, force: true }));
  const root = path.join(base, 'checkout');
  const secret = path.join(base, 'secret.txt');
  await mkdir(path.join(root, 'examples', 'nested'), { recursive: true });
  await mkdir(path.join(root, '.git'), { recursive: true });
  await writeFile(secret, 'TOP SECRET');
  await writeFile(path.join(root, 'examples', 'nested', 'resource.tf'), 'resource "x" "y" {}');
  await symlink(secret, path.join(root, 'examples', 'leak.tf'));
  await symlink(base, path.join(root, 'examples', 'escape'));
  await writeFile(path.join(root, '.git', 'HEAD'), `${'a'.repeat(40)}\n`);

  const tree = await SourceTree.open('fixture', root);
  assert.equal(await tree.readText('examples/nested/resource.tf'), 'resource "x" "y" {}');
  assert.equal(await tree.readText('examples/missing.tf'), undefined);
  await assert.rejects(tree.readText('examples/leak.tf'), /is a symbolic link/);
  await assert.rejects(tree.readText('examples/escape/secret.txt'), /resolves outside the checkout/);
  await assert.rejects(tree.readText('../secret.txt'), /unsafe path/);
  await assert.rejects(tree.readText(secret), /unsafe path/);
  assert.deepEqual(await tree.listFiles('examples', () => true), ['examples/nested/resource.tf']);
  assert.equal(await tree.gitCommit(), 'a'.repeat(40));
});

test('only sources.ts uses the network, and it runs nothing but git', async () => {
  const read = (file) => readFile(new URL(`./${file}`, import.meta.url), 'utf8');
  // The CLI, the parsers and the confined reader never fetch, spawn or evaluate anything.
  for (const file of ['generate-terraform-docs.ts', 'terraform-provider.ts', 'source-tree.ts']) {
    const source = await read(file);
    assert.doesNotMatch(source, /node:(?:child_process|http|https|net|dgram|worker_threads|vm)\b/, file);
    assert.doesNotMatch(source, /\bfetch\(|\beval\(|new Function\(|\bimport\(/, file);
  }
  const sources = await read('sources.ts');
  assert.doesNotMatch(sources, /\beval\(|new Function\(|\bimport\(|\b(?:exec|spawn|fork)(?:Sync)?\(|shell:/);
  assert.deepEqual(
    [...sources.matchAll(/\bexecFileSync\(\s*'([^']+)'/g)].map(([, command]) => command),
    ['git'],
  );
});

