/**
 * Shared String Utilities
 *
 * Provides common string manipulation functions for code generation.
 */

/**
 * Indent each line of a string by a specified number of spaces.
 *
 * @param text - The text to indent
 * @param spaces - Number of spaces to indent (default 2)
 * @returns Indented text
 */
export function indent(text: string, spaces = 2): string {
  const prefix = ' '.repeat(spaces);
  return text
    .split('\n')
    .map((line) => (line ? prefix + line : line))
    .join('\n');
}

/**
 * Remove leading/trailing blank lines from a string.
 *
 * @param text - The text to trim
 * @returns Trimmed text
 */
export function trimBlankLines(text: string): string {
  const lines = text.split('\n');

  // Remove leading blank lines
  while (lines.length > 0 && lines[0]?.trim() === '') {
    lines.shift();
  }

  // Remove trailing blank lines
  while (lines.length > 0 && lines[lines.length - 1]?.trim() === '') {
    lines.pop();
  }

  return lines.join('\n');
}

/**
 * Wrap text at a specified line length.
 *
 * @param text - The text to wrap
 * @param maxLength - Maximum line length (default 80)
 * @returns Wrapped text
 */
export function wrapText(text: string, maxLength = 80): string {
  const words = text.split(' ');
  const lines: string[] = [];
  let currentLine = '';

  for (const word of words) {
    if (currentLine.length + word.length + 1 <= maxLength) {
      currentLine += (currentLine ? ' ' : '') + word;
    } else {
      if (currentLine) lines.push(currentLine);
      currentLine = word;
    }
  }

  if (currentLine) lines.push(currentLine);
  return lines.join('\n');
}

/**
 * Escape a string for use in a JavaScript/TypeScript string literal.
 *
 * @param text - The text to escape
 * @returns Escaped text safe for string literals
 */
export function escapeString(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
}

/**
 * Generate a unique identifier from a string.
 * Useful for generating variable names or IDs.
 *
 * @param text - The text to convert
 * @returns A valid identifier string
 */
export function toIdentifier(text: string): string {
  return text
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .replace(/^(\d)/, '_$1')
    .replace(/__+/g, '_')
    .replace(/^_|_$/g, '');
}

/**
 * Pluralize a word (simple English rules).
 *
 * @param word - The word to pluralize
 * @param count - Optional count to determine singular/plural
 * @returns Pluralized word
 */
export function pluralize(word: string, count?: number): string {
  if (count === 1) return word;

  if (word.endsWith('s') || word.endsWith('x') || word.endsWith('ch') || word.endsWith('sh')) {
    return word + 'es';
  }
  if (word.endsWith('y') && !/[aeiou]y$/i.test(word)) {
    return word.slice(0, -1) + 'ies';
  }
  return word + 's';
}

/**
 * Singularize a word (simple English rules).
 *
 * @param word - The word to singularize
 * @returns Singular form of the word
 */
export function singularize(word: string): string {
  if (word.endsWith('ies')) {
    return word.slice(0, -3) + 'y';
  }
  if (
    word.endsWith('es') &&
    (word.endsWith('ses') || word.endsWith('xes') || word.endsWith('ches') || word.endsWith('shes'))
  ) {
    return word.slice(0, -2);
  }
  if (word.endsWith('s') && !word.endsWith('ss')) {
    return word.slice(0, -1);
  }
  return word;
}

/**
 * Generate a header comment for generated files.
 *
 * @param generatorName - Name of the generator (e.g., 'worker', 'sdk')
 * @returns Header comment string
 */
export function generatedFileHeader(generatorName: string): string {
  return `// Generated by ${generatorName} transformer
// DO NOT EDIT - This file is auto-generated
`;
}
