use std::borrow::Cow;
use std::collections::HashSet;
use std::fs;
use std::path::{Component, Path};

use rayon::prelude::*;

use crate::{Forge, Namespace};

pub mod ts;
#[cfg(feature = "wasm")]
pub mod wasm;

/// The error that plugins, files, [`run`] and [`write()`] return.
pub type Err = Box<dyn std::error::Error + Send + Sync + 'static>;

/// A plugin that generates files.
pub trait Plugin: Sync {
    type File: File; // Might be too restrictive, but we can box the file if needed.

    /// Generates files for the given forge.
    ///
    /// This will be called exactly once.
    fn generate(&self, _: &Forge) -> Result<impl Iterator<Item = Self::File>, Err> {
        Ok(std::iter::empty())
    }

    /// Generates files for the given namespace.
    ///
    /// This will be called exactly once for each namespace and in parallel with other namespaces.
    fn generate_namespace(&self, namespace: Namespace<'_>) -> Result<impl Iterator<Item = Self::File>, Err> {
        #[expect(deprecated, reason = "the default preserves old Plugin implementations")]
        self.generate_group(namespace)
    }

    /// Generates files for the given namespace.
    #[deprecated(note = "use `generate_namespace` instead")]
    fn generate_group(&self, _: Namespace<'_>) -> Result<impl Iterator<Item = Self::File>, Err> {
        Ok(std::iter::empty())
    }
}

/// A file generated by a plugin.
pub trait File: Send {
    /// Path of the file relative to the output directory, using `/` as a separator.
    fn path(&self) -> &str;
    /// Content of the file. [`write()`] skips a file with no content.
    fn content(&self) -> Result<Cow<'_, [u8]>, Err>;
}

/// Runs `plugin` on `forge` and returns every file it generates.
///
/// Calls [`Plugin::generate`] once, then [`Plugin::generate_namespace`] for each
/// namespace in parallel. The files from `generate` come first, then each
/// namespace's files in the order of [`Forge::namespaces`].
pub fn run<P: Plugin>(forge: &Forge, plugin: &P) -> Result<Vec<P::File>, Err> {
    let mut files: Vec<P::File> = plugin.generate(forge)?.collect();

    let namespaces: Vec<Namespace<'_>> = forge.namespaces().collect();
    let per_namespace = namespaces
        .par_iter()
        .map(|&namespace| Ok(plugin.generate_namespace(namespace)?.collect::<Vec<_>>()))
        .collect::<Result<Vec<_>, Err>>()?;

    files.extend(per_namespace.into_iter().flatten());
    Ok(files)
}

/// Writes `files` into `dir`, creating `dir` and any subdirectories the
/// files need. It skips files with no content, overwrites files that
/// already exist, and leaves everything else in `dir` alone.
///
/// Before writing anything, it checks that every path is relative, uses `/`
/// as a separator, and has no empty, `.` or `..` parts, and that no two
/// files share a path.
///
/// It renders every file's content in parallel before writing any of them,
/// so a failing [`File::content`] leaves `dir` untouched. The writes run in
/// parallel too, and a failed write can leave other files already written.
/// If several calls fail, it returns one of their errors.
pub fn write<F: File>(dir: impl AsRef<Path>, files: Vec<F>) -> Result<(), Err> {
    let dir = dir.as_ref();

    let mut paths = HashSet::with_capacity(files.len());
    for file in &files {
        let path = file.path();
        check(path)?;
        if !paths.insert(path) {
            return Err(format!("{path:?} is generated more than once").into());
        }
    }

    let rendered = files
        .into_par_iter()
        .map(|file| {
            let content = file.content().map_err(|err| format!("{}: {err}", file.path()))?;
            let content = content.into_owned();
            Ok((file, content))
        })
        .filter(|rendered| !matches!(rendered, Ok((_, content)) if content.is_empty()))
        .collect::<Result<Vec<_>, Err>>()?;

    // Directories are made first, once each, so files can be written in
    // any order.
    let parents: HashSet<&str> = rendered
        .iter()
        .filter_map(|(file, _)| file.path().rsplit_once('/').map(|(parent, _)| parent))
        .collect();
    fs::create_dir_all(dir).map_err(|err| format!("{}: {err}", dir.display()))?;
    for parent in parents {
        fs::create_dir_all(dir.join(parent)).map_err(|err| format!("{parent}: {err}"))?;
    }

    rendered.into_par_iter().try_for_each(|(file, content)| {
        let path = file.path();
        fs::write(dir.join(path), content).map_err(|err| format!("{path}: {err}"))?;
        Ok(())
    })
}

/// Checks that `path` is relative, uses `/` as a separator, and has no
/// empty, `.` or `..` parts, so joining it onto a directory can't escape
/// that directory.
fn check(path: &str) -> Result<(), Err> {
    // Each part must be a single plain component on this platform, which
    // also rules out a `\` separator or a drive prefix on Windows.
    let valid = path.split('/').all(|part| {
        let mut components = Path::new(part).components();
        matches!(components.next(), Some(Component::Normal(c)) if c == part) && components.next().is_none()
    });
    if valid {
        Ok(())
    } else {
        Err(format!("{path:?} is not a relative path with `/` separators").into())
    }
}
